CREATE TABLE CONVERSAS (
    id_conversas NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno NUMBER NULL, 
    titulo_chat VARCHAR2(255) DEFAULT 'Nova Conversa',
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conv_aluno FOREIGN KEY (id_aluno) REFERENCES ALUNOS(id_aluno)
);

CREATE TABLE MENSAGENS (
    id_mensagem NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conversas NUMBER NOT NULL,
    remetente VARCHAR2(50) NOT NULL, 
    conteudo CLOB NOT NULL,
    tokens_utilizados NUMBER DEFAULT 0,
    data_envio TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_msg_conversas FOREIGN KEY (id_conversas) REFERENCES CONVERSAS(id_conversas) ON DELETE CASCADE,
    CONSTRAINT chk_remetente CHECK (remetente IN ('user', 'assistant', 'system'))
);

CREATE INDEX idx_mensagens_conversas ON MENSAGENS(id_conversas, data_envio);

