CREATE DATABASE EcoCampus;
Use EcoCampus;

CREATE TABLE CURSOS (
    id_curso NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150) NOT NULL,
    area VARCHAR2(100),
    turno VARCHAR2(50),
    campus VARCHAR2(100) 
);

CREATE TABLE MATERIAIS (
    id_material NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    nivel_nocivo VARCHAR2(50),
    pontos_por_kg NUMBER(10,2) NOT NULL,
    unidade VARCHAR2(20) DEFAULT 'kg'
);

CREATE TABLE CICLOS (
    id_ciclo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    data_inicio_coleta DATE,
    data_fim_coleta DATE,
    data_inicio_analise DATE,
    data_fim_analise DATE,
    data_final DATE,
    status VARCHAR2(50)
);

CREATE TABLE LIXEIRAS (
    id_lixeira NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_identificacao VARCHAR2(50) UNIQUE NOT NULL, 
    localizacao VARCHAR2(150) NOT NULL,
    status VARCHAR2(20) DEFAULT 'Ativa',
    CONSTRAINT chk_status_lixeira CHECK (status IN ('Ativa', 'Manutencao', 'Inativa'))
);


CREATE TABLE ALUNOS (
    id_aluno NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso NUMBER NOT NULL,
    nome VARCHAR2(150) NOT NULL,
    email VARCHAR2(150) UNIQUE NOT NULL,
    matricula VARCHAR2(50) UNIQUE NOT NULL,
    data_inscricao DATE DEFAULT SYSDATE,
    CONSTRAINT fk_alunos_curso FOREIGN KEY (id_curso) REFERENCES CURSOS(id_curso)
);

CREATE TABLE RESPONSAVEIS (
    id_responsavel NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150) NOT NULL,
    email VARCHAR2(150) UNIQUE NOT NULL,
    senha_hash VARCHAR2(255) NOT NULL,
    tipo VARCHAR2(50) NOT NULL, 
    id_curso NUMBER,
    data_cadastro DATE DEFAULT SYSDATE,
    CONSTRAINT fk_respons_curso FOREIGN KEY (id_curso) REFERENCES CURSOS(id_curso),
    CONSTRAINT chk_tipo_respons CHECK (tipo IN ('Aluno', 'Professor', 'Coordenador'))
);

CREATE TABLE ENTREGAS (
    id_entrega NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno NUMBER NOT NULL,
    id_material NUMBER NOT NULL,
    id_ciclo NUMBER NOT NULL,
    id_lixeira NUMBER NOT NULL,
    url_foto VARCHAR2(500) NOT NULL,
    quantidade_kg NUMBER(10,3),
    data_entrega DATE DEFAULT SYSDATE,
    status VARCHAR2(20) DEFAULT 'Pendente',
    observacao VARCHAR2(500),
    id_responsavel_aprovador NUMBER,
    data_aprovacao DATE,
    CONSTRAINT fk_entregas_aluno FOREIGN KEY (id_aluno) REFERENCES ALUNOS(id_aluno),
    CONSTRAINT fk_entregas_material FOREIGN KEY (id_material) REFERENCES MATERIAIS(id_material),
    CONSTRAINT fk_entregas_ciclo FOREIGN KEY (id_ciclo) REFERENCES CICLOS(id_ciclo),
    CONSTRAINT fk_entregas_lixeira FOREIGN KEY (id_lixeira) REFERENCES LIXEIRAS(id_lixeira),
    CONSTRAINT fk_entregas_respons FOREIGN KEY (id_responsavel_aprovador) REFERENCES RESPONSAVEIS(id_respons),
    CONSTRAINT chk_status_entrega CHECK (status IN ('Pendente', 'Aprovado', 'Rejeitado'))
);

CREATE TABLE PONTUACOES_CICLO (
    id_pont_ciclo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno NUMBER NOT NULL,
    id_ciclo NUMBER NOT NULL,
    total_pontos NUMBER(10,2) DEFAULT 0,
    total_entregas NUMBER DEFAULT 0,
    data_calculo DATE DEFAULT SYSDATE,
    CONSTRAINT fk_pont_ciclo_aluno FOREIGN KEY (id_aluno) REFERENCES ALUNOS(id_aluno),
    CONSTRAINT fk_pont_ciclo_ciclo FOREIGN KEY (id_ciclo) REFERENCES CICLOS(id_ciclo),
    CONSTRAINT uq_aluno_ciclo UNIQUE (id_aluno, id_ciclo)
);

CREATE TABLE PONTUACOES_GERAIS (
    id_aluno NUMBER PRIMARY KEY,
    total_pontos NUMBER(10,2) DEFAULT 0,
    total_entregas NUMBER DEFAULT 0,
    total_entregas_aprovadas NUMBER DEFAULT 0,
    ultima_atualizacao DATE DEFAULT SYSDATE,
    CONSTRAINT fk_pont_gerais_aluno FOREIGN KEY (id_aluno) REFERENCES ALUNOS(id_aluno)
);

CREATE TABLE RANKING_HISTORICO (
    id_ranking NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno NUMBER NOT NULL,
    id_ciclo NUMBER NOT NULL,
    posicao NUMBER,
    total_pontos NUMBER(10,2),
    data_calculo DATE DEFAULT SYSDATE,
    CONSTRAINT fk_ranking_aluno FOREIGN KEY (id_aluno) REFERENCES ALUNOS(id_aluno),
    CONSTRAINT fk_ranking_ciclo FOREIGN KEY (id_ciclo) REFERENCES CICLOS(id_ciclo),
    CONSTRAINT uq_ranking_ciclo_aluno UNIQUE (id_ciclo, id_aluno)
);

CREATE TABLE GANHADORES_CERTIFICADO (
    id_ganhador NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno NUMBER NOT NULL,
    id_ciclo NUMBER NOT NULL,
    total_pontos NUMBER(10,2),
    posicao_final NUMBER,
    data_confirmacao DATE DEFAULT SYSDATE,
    horas_complementares NUMBER, -- O valor foi flexibilizado, preencha no momento da emissão
    certificado_emitido CHAR(1) DEFAULT 'N',
    CONSTRAINT fk_ganhadores_aluno FOREIGN KEY (id_aluno) REFERENCES ALUNOS(id_aluno),
    CONSTRAINT fk_ganhadores_ciclo FOREIGN KEY (id_ciclo) REFERENCES CICLOS(id_ciclo)
);


CREATE TABLE CONVERSAS (
    id_conversas NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno NUMBER NULL, 
    titulo_chat VARCHAR2(255) DEFAULT 'Nova Conversa',
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conv_aluno FOREIGN KEY (id_aluno) REFERENCES ALUNOS(id_aluno)
);

CREATE TABLE MENSAGENS (
    id_mensagem NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conversas NUMBER NOT NULL,
    remetente VARCHAR2(50) NOT NULL, 
    conteudo CLOB NOT NULL,
    tokens_utilizados NUMBER DEFAULT 0,
    data_envio TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_msg_conversas FOREIGN KEY (id_conversas) REFERENCES CONVERSAS(id_conversas) ON DELETE CASCADE,
    CONSTRAINT chk_remetente CHECK (remetente IN ('user', 'assistant', 'system'))
);

CREATE INDEX idx_mensagens_conversas ON MENSAGENS(id_conversas, data_envio);

